"""Independently run Ascon-C's 11 GenKAT executables and compare official vectors.

Run from the Ascon-bench repository root:
    python verify_all_ascon_tests.py

Requires only Python's standard library. Does not modify upstream ascon-c code.
"""

from __future__ import annotations

import hashlib
import platform
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build" / "cmake"
UPSTREAM = ROOT / "ascon-c"
RESULTS_FILE = ROOT / "docs" / "kat_validation_windows.txt"

# (executable name without .exe, upstream algorithm directory, expected KAT file)
CASES = [
    ("genkat_crypto_hash_asconhash256_ref", "crypto_hash/asconhash256", "LWC_HASH_KAT_128_256.txt"),
    ("genkat_crypto_hash_asconhash256_opt64", "crypto_hash/asconhash256", "LWC_HASH_KAT_128_256.txt"),
    ("genkat_crypto_hash_asconxof128_ref", "crypto_hash/asconxof128", "LWC_XOF_KAT_128_512.txt"),
    ("genkat_crypto_hash_asconxof128_opt64", "crypto_hash/asconxof128", "LWC_XOF_KAT_128_512.txt"),
    ("genkat_crypto_cxof_asconcxof128_ref", "crypto_cxof/asconcxof128", "LWC_CXOF_KAT_128_512.txt"),
    ("genkat_crypto_auth_asconmacv13_ref", "crypto_auth/asconmacv13", "LWC_MAC_KAT_128_128.txt"),
    ("genkat_crypto_auth_asconmacv13_opt64", "crypto_auth/asconmacv13", "LWC_MAC_KAT_128_128.txt"),
    ("genkat_crypto_auth_asconprfv13_ref", "crypto_auth/asconprfv13", "LWC_PRF_KAT_128_512.txt"),
    ("genkat_crypto_auth_asconprfv13_opt64", "crypto_auth/asconprfv13", "LWC_PRF_KAT_128_512.txt"),
    ("genkat_crypto_auth_asconprfsv13_ref", "crypto_auth/asconprfsv13", "LWC_PRFS_KAT_128_128.txt"),
    ("genkat_crypto_auth_asconprfsv13_opt64", "crypto_auth/asconprfsv13", "LWC_PRFS_KAT_128_128.txt"),
]


def normalized_bytes(path: Path) -> bytes:
    """Ignore CRLF vs LF line endings, just as CTest's --ignore-eol does."""
    return path.read_bytes().replace(b"\r\n", b"\n")


def git_hash(repo: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            text=True, stderr=subprocess.DEVNULL, timeout=10
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return "unavailable"


def main() -> int:
    if not BUILD.is_dir() or not UPSTREAM.is_dir():
        print("ERROR: Put this file in your Ascon-bench repository root, beside 'ascon-c'.")
        print(f"Expected build folder: {BUILD}")
        return 2

    lines = [
        "Ascon-C official known-answer test verification (11 selected configurations)",
        "Executed locally by: " + platform.node(),
        "Local timestamp: " + datetime.now().astimezone().isoformat(timespec="seconds"),
        "Python: " + sys.version.split()[0],
        "OS: " + platform.platform(),
        "Team Git commit: " + git_hash(ROOT),
        "Ascon-C submodule commit: " + git_hash(UPSTREAM),
        "Method: execute each compiled GenKAT binary; compare its complete generated output",
        "against the matching official Ascon-C KAT file, normalizing CRLF/LF only.",
        "This is correctness testing, not a performance benchmark.",
        "",
    ]
    passed = 0
    for number, (name, upstream_folder, expected_file) in enumerate(CASES, 1):
        executable = BUILD / (name + (".exe" if sys.platform == "win32" else ""))
        if not executable.exists():
            fallback = BUILD / name
            if fallback.exists():
                executable = fallback
        actual = BUILD / expected_file
        expected = UPSTREAM / upstream_folder / expected_file
        label = f"{number:02d}/11 {name}"
        error = None
        actual_hash = ""
        try:
            if not executable.is_file():
                raise FileNotFoundError(f"Executable not found: {executable}")
            if not expected.is_file():
                raise FileNotFoundError(f"Official KAT not found: {expected}")
            # Do not accidentally pass because of a stale KAT generated by a different executable.
            if actual.exists():
                actual.unlink()
            proc = subprocess.run(
                [str(executable)], cwd=BUILD, capture_output=True,
                text=True, errors="replace", timeout=120, check=False
            )
            if proc.returncode != 0:
                raise RuntimeError(
                    f"GenKAT exit code {proc.returncode}; "
                    f"stdout={proc.stdout[-300:]!r}; stderr={proc.stderr[-300:]!r}"
                )
            if not actual.is_file():
                raise FileNotFoundError(f"GenKAT did not generate: {actual}")
            generated_bytes = normalized_bytes(actual)
            official_bytes = normalized_bytes(expected)
            actual_hash = hashlib.sha256(generated_bytes).hexdigest()
            if generated_bytes != official_bytes:
                raise ValueError(
                    f"KAT output mismatch (generated {len(generated_bytes)} bytes, "
                    f"official {len(official_bytes)} bytes)"
                )
        except (OSError, RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
            error = str(exc)

        if error is None:
            passed += 1
            result = f"PASS {label} | SHA256(normalized KAT)={actual_hash}"
        else:
            result = f"FAIL {label} | {error}"
        print(result, flush=True)
        lines.append(result)

    summary = f"FINAL RESULT: {passed}/{len(CASES)} passed"
    print("\n" + summary)
    lines.extend(["", summary])
    RESULTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Evidence saved to:", RESULTS_FILE)
    return 0 if passed == len(CASES) else 1


if __name__ == "__main__":
    raise SystemExit(main())
